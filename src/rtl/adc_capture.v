`timescale 1ns / 1ps
//=============================================================================
//  adc_capture.v  ——  AD9238 采集通路(2026-10-06 新增)
//
//  【本模块要解决的三个问题】
//    ① ADC 采样时钟从哪来、怎么调
//    ② 数据在什么时刻抓才落在数据眼中心
//    ③ 抓到的点怎么被 PS 读走(2026-10-14 起是 A/B 交织的 16384 个)
//
//------------------------------------------------------------------------------
//  ① 采样时钟:130 MHz 基础时钟 + 整数分频器
//------------------------------------------------------------------------------
//  基础时钟 clk_base = 130 MHz,由 cv_sys 里的 MMCM 产生(VCO 1300 / 10)。
//  ADC 时钟 adc_clk = clk_base / P,P 是 8 位寄存器字段,运行时可改。
//
//    P    adc_clk      说明
//    2    65   MHz   ← AD9238-65 的额定上限,【2026-10-07 换排线后实测可用】
//    4    32.5 MHz
//    5    26   MHz
//    10   13   MHz
//    13   10   MHz   ← 复位默认(130/13)
//    26    5   MHz
//    65    2   MHz
//    130   1   MHz
//
//  🔴 为什么基础时钟取 130 而不是直接取 65:
//     65 = 5 × 13 是质因数分解的**死结** —— 任何从 65 MHz 分频出来的频率
//     都只能是 65/n,而 65/10 = 6.5 不是整数 ⇒ **拿不到 10 MHz**。
//     要同时够到 65 和 10,基础时钟必须是二者的公倍数 ⇒ 130 是最小公倍数。
//     (这是 2026-10-06 用户与 Claude 一起推出来的;此前一版错误地写成了
//      "两个 MMCM + BUFGMUX 切换",被用户一句"写个分频器不行吗"推翻。)
//
//  ⚠️ 上限口径:adc_clk 最高 65 MHz(AD9238-65 额定)。P 的下限钳在 2。
//
//  🔴 **P=2(65 MHz)可用性 —— 2026-10-07 实测更新,原判断已作废**
//     原文:「杜邦线 tPD 离散度 ~4 ns 盖过 3.7 ns 数据眼 ⇒ 65 MHz 接不出来;
//            要跑需 ① 排线/等长走线 ② 加 IDELAYE2」。
//     实测:用户换 2×9 排线后,**只做 ① 就够了,② 不需要** ——
//           DIV=2 下 `0x90 = 3`(mmcm_locked=1 / done=1),采集 0.0022 s 完成;
//           PH_OFF=0 → p-p=42,250 点里 3.85 个周期,干净正弦;
//           解调幅值 18.50 码 vs 10 MSPS 下同一路 1 MHz 的 18.18 码(差 1.8%)。
//     证据:`report/measurements/20261007_adc_65msps_waveforms.png` / `_board_dump.out`。
//     ⇒ **本模块的 RTL 从未挡住 65 MHz**,不用改逻辑。当时挡住的是软件侧刻度
//       (见 ② 末段),以及接线。
//
//     ⚠️ 遗留的真限制:P=2 的可达刻度只有 `{-1, 0}` 两个(全范围扫过),
//        没有余量做细调 —— 这一条是真的,但仍**不需要 IDELAYE2**,
//        因为其中一个刻度实测就是好的。
//
//------------------------------------------------------------------------------
//  ② 采样时刻:以 adc_clk 下降沿为基准的可调偏移
//------------------------------------------------------------------------------
//  adc_clk 由计数器 cnt(0..P-1)组合产生:cnt < P/2 时为高。
//  ⇒ 上升沿在 cnt == 0,下降沿在 cnt == P/2。
//
//  AD9238 的时序:上升沿采样,数据在 tPD 后更新(本模块手册给 ≈2 ns),
//  一直保持到下一个上升沿之后 tPD。⇒ 在一个周期内,数据有效窗口是
//  [tPD, P·T + tPD],中心在 P·T/2 + tPD —— **就是下降沿附近**。
//
//  ⇒ 默认采样刻度 = 下降沿(cnt == P/2),PH_OFF 是相对它的**有符号偏移**,
//    单位是一个 clk_base 周期(7.69 ns)。
//    用"相对下降沿"而不是"绝对刻度",好处是 P 改变时默认位置**自动跟着走**,
//    PS 不必在改分频比之后再算一遍相位。
//
//  ⚠️ 7.69 ns 一格的分辨力,只在低 P 时够用:
//       P=13(10 MHz,周期 100 ns)→ 13 个可调点,每点 7.7 ns,够精调
//       P=2 (65 MHz,周期 15.4 ns)→ 只有 2 个点,每点 = 半个周期 ⇒ **没有余量**
//
//  🔴 **「所以必须配 IDELAYE2」这句已作废(2026-10-07 实测)。**
//     "没有余量"和"不可用"是两回事:两个刻度里 `0` 实测就是干净的
//     (p-p=42 的正弦),所以**不微调也能用**。IDELAYE2 是"想再挪细一点"的
//     升级项,不是"能不能跑起来"的前置条件。
//     真正的前置条件是**软件侧的刻度折回** —— P=2 时窗 [2−P/2,+1] = [1,1]
//     与寄存器合法范围 [-1,0] 不相交,不折回就永远命中不了。
//     修在 `pynq_regs.h::cv_adc_phase_center()` / `measure_config.c::adc_window()`。
//
//------------------------------------------------------------------------------
//  ③ 缓冲与读出:双时钟 BRAM,不做 CDC 逻辑
//------------------------------------------------------------------------------
//  16384 × 16 bit 简单双口 BRAM:
//      写口  clk_base(130 MHz)—— 采集
//      读口  clk_axi ( 50 MHz)—— PS 经 AXI-Lite 按索引读
//  ⇒ 数据本身**不需要任何 CDC 同步器** —— 双口 BRAM 就是标准的跨时钟域存储器。
//  需要同步的只有几个标量状态位(done / busy / otr),各走两级同步器。
//
//  ⚠️ 读口是**寄存器输出**(BRAM 的标准形态),所以 rd_data 比 rd_idx 晚一拍。
//     对本用途无影响:PS 先写索引、再下一笔读数据,中间隔了远不止一拍。
//     (改成组合读会在 LUTRAM 里展开 16384×12 —— 那是 49152 个 LUT,不可接受。)
//
//  🔴 **布局是交织的**(2026-10-14 起,见下面 ④):
//        [0]=A₀ [1]=B₀ [2]=A₁ [3]=B₁ … [2k]=A_k [2k+1]=B_k
//     偶数地址 = A(INA)、奇数地址 = B(INB),**同一 k 来自同一个转换**。
//     ⛔ 所以 PS 侧必须拆交织 —— 把整块当一路解调会得到"两路交替"的垃圾,
//        而且它**看起来仍像正弦**(频率是一半),不报错。判据:两路各自的
//        峰峰值都在合理量级、且解调幅值不随重采跳变。
//
//  ⚠️ 一个字 16 位,而不是 12 位:多出来的 4 位装 OTR 溢出标志。
//     16384×16 = 256 Kb ⇒ 8 个 BRAM36(2026-10-08 由 4096→8192 加长;
//     2026-10-14 因 A/B 成对交织再 8192→16384)。
//
//------------------------------------------------------------------------------
//  ④ 双通道成对采集(A 在偶地址、B 在奇地址)—— 2026-10-14 新增
//------------------------------------------------------------------------------
//  【为什么必须这么做】
//    AD9238 的两路是**同一个转换沿上同时采**的两个 S/H,产生**一对同步样本**;
//    那 12 位总线只是把它们**时分复用**送出(前半个周期 INA、后半个周期 INB)。
//    也就是说:**同步的那一对数据本来就在线上,一个 tick 之遥。**
//
//    本模块 2026-10-14 之前 `samp_en = (tick == ph_off)` —— 每个 ADC 周期
//    只命中**一个** tick ⇒ 把另一半**扔了**。要拿另一路只能**再发一次 GO**
//    (中间隔着一万多个转换周期),于是两次采集的**相位原点不同**
//    (解调基准锚在各次采集的第 0 点)⇒ 两路之间的相位差是**随机的**,
//    软件只能比幅值。
//
//    ⇒ 代价是:Cs 只能按"被测件是纯电容"近似,**Cp / D 算不出来**(恒显示 `--`),
//      RG 回路(栅极电阻)更没有算法可用 —— 它要的正是 VH/VL 的相对相位。
//      前序 STM32 工程 `ad9238_capture.c` 的 `AD9238_Deinterleave` 就是靠
//      "两数组对应同一转换周期"算复阻抗的(见 `report/llm-log/LLM-062.md`)。
//
//  【怎么改】
//    ① `ph_b`(B 窗中心)= `ph_off`(A 窗中心)+ **P/2**,再折回寄存器合法范围。
//       物理含义直白:**B 窗中心就在 A 窗中心后面半个 ADC 周期**。
//       ⛔ **由本模块推,不让软件再写第二个刻度** —— 寄存器里只有一个 PH_OFF,
//          而"两个独立舍入出来的中心"迟早会与这里不一致(那就是两个真相)。
//    ② A、B 各走**自己的写指针**,地址分别固定落在**偶 / 奇**位置:
//          A → {wr_a, 1'b0}      B → {wr_b, 1'b1}
//       ⛔ **不能写成 `wr_ptr` 与 `wr_ptr+1`** —— 那只在"A 窗先于 B 窗命中"时
//          成立,而**折回之后并非总是如此**:P=4 时 A 中心 = +1、B 中心折回成 −1,
//          B 先命中。用两个独立指针,布局就与命中先后**无关**。
//    ③ 缓冲区总长 = 2 × 每通道点数;每通道仍是 `BUF_DEPTH/2` 点、均匀采样
//       (每周期恰好一次)⇒ 采样率口径**不变**,仍是 `clk_base / P`。
//
//  【相位原点:为什么成对之后就能算相位了】
//    两路的第 k 个样本来自**同一个转换 k**(同一个采样瞬间),而我们**不在
//    两边各加任何时间改正** —— 因为硬件上本来就没有时间差。解调用的参考相位
//    对两路是同一个(`cos(2πMk/L)`,k 从 0 起),⇒ 两路解出来的 I/Q
//    **天然在同一个相位参考系里**,`atan2` 之差就是被测件的真实相移。
//    ⇒ C 侧可以直接算 `Z = R0·(VH−VL)/VL`(复数),`Cs` 取 `−1/(ω·Im Z)`、
//      `Rg` 取 `Re Z`,不再需要"纯电容"那个近似。
//
//  【仍未验证的一条,别当成已证】
//    "一个 adc_clk 周期内先后送出的这两个字**属于同一个转换**"——
//    P=2 由实测支持(`report/llm-log/LLM-045.md` §G:A 在 tick −1、B 在 tick 0),
//    且与前序 STM32 工程的做法一致。**其余 P 值未逐一验证**;
//    要换 DIV 请先按 `docs/acquisition_demod.md` 的办法把窗口重新扫一遍。
//
//  ⚠️ **与 C 侧 `cv_adc_phase_center_b()` 的分工(2026-10-14)**
//    窗口宽度是 P/2 个 tick ⇒ 窗内**不止一个**合法刻度,取哪个都落在 B 的
//    数据窗里。本模块取 `A + P/2`(**恒定半个 ADC 周期**),C 侧那个函数独立地
//    对"物理中心 1.5+P/4"取整 —— **P 为奇数时两者会差一个 tick**:
//      P=13 → 本模块 B = +4,C 侧 = +5(两者都在窗 [2,7] 内,都不算错)
//      P=2  → 两者都是 0 ✓(当前三档激励**只用 P=2**,见 §八)
//    ⇒ **硬件是本模块出的,以本模块为准**;`cv_adc_phase_center_b()` 自此
//      降级为**参考资料**,C 侧不再有调用方(§三 之后 B 的刻度由硬件自推)。
//
//  资源:8192×2×16 bit = 256 Kb ⇒ 8 个 BRAM36(原 4 个)。
//------------------------------------------------------------------------------
//  采集模式
//------------------------------------------------------------------------------
//   单次(CONT=0):PS 写 GO → 清指针、置 busy → 收满 16384 字(每路 8192)→ done=1、busy=0
//                  PS 轮询 STS.done,然后慢慢读。缓冲**【冻结】**,不会读着读着变。
//   自由(CONT=1):连续绕圈写,收满第一圈后 done=1。PS 读到的可能是撕裂的快照
//                  —— 用于"看波形是不是在动"的活体检查,不适合定量测量。
//
//  ⚠️ 单次模式下读缓冲是安全的(已冻结);自由模式下不保证。
//
//------------------------------------------------------------------------------
//  【时钟域清单】——改代码前先看这里
//    clk_base 域:cnt / P / PH_OFF / wr_a / wr_b / wr_n / busy / done / otr_sticky / BRAM 写口
//    clk_axi  域:所有 cfg_* 寄存器、rd_idx、BRAM 读口、sts_*
//    cfg_* → clk_base : 两级同步(go 另加沿检测)
//    busy/done/otr    → clk_axi : 两级同步
//                         ↑ 这三条**只是电平**,极性翻转远慢于 50 MHz,两级够
//    BRAM              : 双口,无需同步
//    ⚠️ P 与 PH_OFF 是多位准静态量,走两级同步**不是**格雷码,
//       所以软件必须遵守:改 P / PH_OFF 之前确认不在采集(CONT=0 且 busy=0)。
//       采集途中改会让基础域看到一个瞬时垃圾值 —— 只影响一拍,但没必要冒。
//=============================================================================

module adc_capture #(
    // 复位默认分频比:130 MHz / 2 = 65 MHz(AD9238-65 额定上限)。
    //   🔴 2026-10-08 由 13 改 2。理由:采样率**统一固定 65 MSPS 不再可调**,
    //      而 0x88 的复位值是这块硬件上电后的实际起点 —— 复位若还留 10 MSPS,
    //      就出现"界面说 65、硬件复位到 10"的不一致组合。
    //      配套:`pynq_regs.h::CV_ADC_DIV_DEFAULT` 必须同为 2。
    parameter integer DIV_DEFAULT = 2,
    // 缓冲深度(**交织字总数**)与索引位宽。改深度必须同时改 BUF_AW。
    //   🔴 2026-10-08 由 4096 改 8192。理由:采样率固定 65 MSPS 后,
    //      最低档激励 10 kHz 的解调要求窗覆盖**整数个激励周期**,
    //      gcd(65e6,10e3)=1e4 ⇒ q=6500 ⇒ 窗长至少 6500 点,**4096 装不下**
    //      ⇒ 10 kHz 这一档在 65 MSPS 下原本是"数学上不成立"的组合。
    //   🔴 2026-10-14 由 8192 改 16384(见文件头 ④):A、B 成对交织后
    //      **每通道**才 8192 点。⛔ 不能图省事把它留在 8192 ——
    //      那样每通道只有 4096 点,`L = 4095` 对 1 MHz / 100 kHz 仍成立,
    //      但 **10 kHz 档 q = 6500 > 4096 直接失效**(解调会报
    //      「窗里放不下整数个激励周期」)。三档激励要一起活下来,就得加倍。
    //   ⚠️ 连带必改(三处,漏一处就静默出错):
    //      ① cv_sys.v 的 `.rd_idx (cfg_adc_buf_idx[13:0])`;
    //      ② cv_axi_lite_slave.v 的写掩码 `32'h0000_1FFF` → `0x3FFF`
    //         (不改 ⇒ 索引 ≥8192 被静默截断成另一个地址,读到的**不是**
    //         你要的那个点,且不报错);
    //      ③ C 侧 `adc_sample.h` 的 `ADC_SAMPLE_BUF_DEPTH` / 拆交织。
    //   资源:16384×16 bit = 256 Kb ⇒ 8 个 BRAM36(XC7Z020 共 140 个)。
    parameter integer BUF_DEPTH   = 16384,
    parameter integer BUF_AW      = 14
)(
    //---------------------------------------------------------------------
    // 基础时钟域(130 MHz,来自 cv_sys 的 MMCM)
    //---------------------------------------------------------------------
    input  wire         clk_base,

    // 低有效复位请求 —— **异步置位、同步释放**。
    // 由 cv_sys 给:cfg_clk_release & s_axi_aresetn & mmcm_locked
    //   ⇒ MMCM 没锁住时本模块被按在复位态,不会跑到一个错误的时钟上。
    //   ⚠️ 复位请求里已经含了 mmcm_locked(异步域),所以下面还要一个
    //      mmcm_locked 输入把 lock 状态**单独**同步给 clk_axi 域做状态回读;
    //      两者不是重复:一个是复位门,一个是可读状态。
    input  wire         rst_n_async,
    input  wire         mmcm_locked,       // MMCM 锁定(异步,状态回读用)

    //---------------------------------------------------------------------
    // AXI 时钟域(50 MHz)—— 配置、状态、缓冲读口都在这边
    //---------------------------------------------------------------------
    input  wire         clk_axi,

    //---------------------------------------------------------------------
    // 配置(clk_axi 域,准静态)
    //---------------------------------------------------------------------
    input  wire [7:0]        cfg_div,      // P,分频比,<2 时硬件钳到 2
    input  wire signed [7:0] cfg_ph_off,   // 相对 adc_clk 下降沿的偏移,单位 = clk_base 周期
    input  wire              cfg_cont,     // 1 = 自由运行 / 0 = 单次
    input  wire              cfg_go,       // clk_axi 域 1 拍脉冲,启动一次单次采集
    input  wire              cfg_oe_n,     // → adc_oe_n(0 = 使能输出)
    input  wire              cfg_pdn,      // → adc_pdn (1 = 掉电)

    //---------------------------------------------------------------------
    // ADC 物理引脚
    //---------------------------------------------------------------------
    output wire         adc_clk,       // → AD9238 CLK   (T11 / J4-2)
    output wire         adc_oe_n,      // → AD9238 OEB   (V5  / J4-1),低有效,0 = 使能输出
    output wire         adc_pdn,       // → AD9238 PDWN  (Y9  / J4-17),高有效,1 = 掉电
    input  wire [11:0]  adc_d,         // ← AD9238 D0..D11 (V7 U7 W8 V8 U9 U8 U10 T9 W6 V6 Y7 Y6)
    input  wire         adc_otr,       // ← AD9238 OTR   (Y8  / J4-18),溢出标志

    //---------------------------------------------------------------------
    // 状态(clk_axi 域,已同步)
    //---------------------------------------------------------------------
    output wire         sts_mmcm_locked,
    output wire         sts_done,
    output wire         sts_busy,
    output wire         sts_otr,       // 自上次 GO 起是否出现过溢出(粘滞)

    //---------------------------------------------------------------------
    // 缓冲读口(clk_axi 域)
    //---------------------------------------------------------------------
    input  wire [BUF_AW-1:0] rd_idx,
    output wire [11:0]       rd_data,
    output wire              rd_otr
);

    //=========================================================================
    //  0. 复位:异步置位 / 同步释放(clk_base 域)
    //     ⚠️ 后面所有 always 块都用 rst_base_n 作异步复位 —— 它本身是
    //        寄存器输出,置位沿跟着 rst_n_async 走(异步),释放沿被 clk_base
    //        打过拍(同步)。这是 7 系列的教科书写法。
    //=========================================================================
    // ⚠️ 所有同步器寄存器都打 `ASYNC_REG = "TRUE"`(2026-10-06 补)。
    //    作用有两个,缺一不可:
    //      ① 告诉**布局器**把两级触发器放进同一个 slice/相邻 slice ——
    //         亚稳态的传播窗口随两者之间的布线延迟线性增长,分开摆会把
    //         上一级刚稳定的值又抖一次,MTBF 直接掉几个数量级;
    //      ② 告诉**时序分析器**这是同步器 —— 配合 led.xdc 里的
    //         set_clock_groups -asynchronous,不把它当普通数据路径报违规。
    //    ⛔ 只在第二级上打是**没用**的:第一级才是真正会进亚稳态的那颗。
    (* ASYNC_REG = "TRUE" *) reg [1:0] rst_sync;

    always @(posedge clk_base or negedge rst_n_async) begin
        if (!rst_n_async) rst_sync <= 2'b00;
        else              rst_sync <= {rst_sync[0], 1'b1};
    end

    wire rst_base_n = rst_sync[1];

    //=========================================================================
    //  1. 配置量同步到 clk_base 域
    //     ⚠️ 多位准静态量,不用格雷码 —— 前提是软件遵守"改之前先停采集",
    //        见文件头【时钟域清单】。
    //=========================================================================
    (* ASYNC_REG = "TRUE" *) reg [7:0]        div_s1, div_s2;
    (* ASYNC_REG = "TRUE" *) reg signed [7:0] pho_s1, pho_s2;
    (* ASYNC_REG = "TRUE" *) reg              cont_s1, cont_s2;

    always @(posedge clk_base or negedge rst_base_n) begin
        if (!rst_base_n) begin
            div_s1  <= 8'd0;        div_s2  <= 8'd0;
            pho_s1  <= 8'sd0;       pho_s2  <= 8'sd0;
            cont_s1 <= 1'b0;        cont_s2 <= 1'b0;
        end else begin
            div_s1  <= cfg_div;      div_s2  <= div_s1;
            pho_s1  <= cfg_ph_off;   pho_s2  <= pho_s1;
            cont_s1 <= cfg_cont;     cont_s2 <= cont_s1;
        end
    end

    wire signed [7:0] ph_off = pho_s2;
    wire              cont_s = cont_s2;

    // 分频比下限保护:cnt 是 8 位,P 必须 >= 2,否则 cnt == P-1 这条判断
    // 会在 P=0/1 时溢出成永远不自增(计数器卡死)⇒ 钳位是**功能正确性**要求,
    // 不是"防御性编程"。
    wire [7:0] P_raw = div_s2;
    wire [7:0] P     = (P_raw < 8'd2) ? 8'd2 : P_raw;
    wire [7:0] half  = {1'b0, P[7:1]};      // P/2,adc_clk 的下降沿刻度

    //=========================================================================
    //  2. 分频计数器 + adc_clk
    //=========================================================================
    reg [7:0] cnt;

    always @(posedge clk_base or negedge rst_base_n) begin
        if (!rst_base_n)          cnt <= 8'd0;
        else if (cnt >= (P - 8'd1)) cnt <= 8'd0;
        else                      cnt <= cnt + 8'd1;
    end

    // 上升沿在 cnt==0,下降沿在 cnt==half。
    // ⚠️ P 为奇数时占空比不是 50%(如 P=13 是 6/7 = 46%),AD9238 接受,
    //    不为了凑 50% 去限制 P 取偶数 —— 那会让 13、65 这些关键档位消失。
    assign adc_clk = (cnt < half);

    // 静态控制脚:直接由 clk_axi 域寄存器驱动。
    // 这两根是 DC 电平,没有建立/保持要求,不需要同步器。
    assign adc_oe_n = cfg_oe_n;
    assign adc_pdn  = cfg_pdn;

    //=========================================================================
    //  3. 采样刻度
    //     默认(偏移 0)= 下降沿;偏移可正可负,范围受 cnt 的取值域限制,
    //     即有效范围是 [0-half, P-1-half] = [-P/2, P-1-P/2]。
    //     越界的偏移只是永远不命中 ⇒ 采集不到数据(done 永远不置位),
    //     **不会**误触发 —— 失败方向安全。
    //=========================================================================
    wire signed [8:0] cnt_s  = $signed({1'b0, cnt});
    wire signed [8:0] half_s = $signed({1'b0, half});
    wire signed [8:0] tick   = cnt_s - half_s;          // 相对下降沿的刻度

    //-------------------------------------------------------------------------
    // 两个时间槽的中心(见文件头 ④)
    //   A(INA) = ph_off              —— 软件推的 `1.5 − P/4`,折回后写进 0x88
    //   B(INB) = A + P/2,再折回      —— **硬件自己推**,不占第二个寄存器字段
    // 折回范围 = [−P/2, P−1−P/2],共 P 个刻度。A 已在范围内 ⇒ A+half ∈ [0, P−1],
    // ⇒ 至多减**一次** P 就落回范围(与 `cv_adc_phase_center_b()` 同一条折回)。
    //-------------------------------------------------------------------------
    wire signed [8:0] ph_a_s   = $signed(ph_off);
    wire signed [8:0] p_s      = $signed({1'b0, P});
    wire signed [8:0] hi_s     = p_s - 9'sd1 - half_s;   // 寄存器合法上界 P−1−P/2
    wire signed [8:0] ph_b_sum = ph_a_s + half_s;
    wire signed [8:0] ph_b_s   = (ph_b_sum > hi_s) ? (ph_b_sum - p_s) : ph_b_sum;

    wire samp_en_a = (tick == ph_a_s);
    wire samp_en_b = (tick == ph_b_s);
    // ⚠️ 两者**不可能同拍**:ph_b − ph_a ≡ P/2 (mod P),P ≥ 2 ⇒ 至少差一个刻度。
    //    (断言放在 `report/llm-log/LLM-062.md` 的验证表里,不在 RTL 里跑仿真。)

    //=========================================================================
    //  4. GO 脉冲同步 + 沿检测(clk_axi → clk_base)
    //=========================================================================
    (* ASYNC_REG = "TRUE" *) reg go_s1, go_s2, go_s3;

    always @(posedge clk_base or negedge rst_base_n) begin
        if (!rst_base_n) begin
            go_s1 <= 1'b0; go_s2 <= 1'b0; go_s3 <= 1'b0;
        end else begin
            go_s1 <= cfg_go; go_s2 <= go_s1; go_s3 <= go_s2;
        end
    end

    wire go_pulse = go_s2 & ~go_s3;

    //=========================================================================
    //  5. 采集控制
    //=========================================================================
    reg                    busy;
    reg                    done;
    reg                    otr_sticky;

    // ---- 双通道写指针(见文件头 ④)--------------------------------------
    localparam integer CH_AW    = BUF_AW - 1;        // 每通道指针位宽(14−1 = 13)
    localparam integer CH_DEPTH = BUF_DEPTH / 2;     // 每通道点数(8192)
    localparam [CH_AW-1:0] CH_LAST = CH_DEPTH - 1;   // 每通道绕回阈值

    reg [CH_AW-1:0]        wr_a;                    // A(INA)写指针 → 偶地址
    reg [CH_AW-1:0]        wr_b;                    // B(INB)写指针 → 奇地址
    reg [BUF_AW-1:0]       wr_n;                    // 总写入数,判满用(0..BUF_DEPTH−1)

    // ⚠️ 两个独立指针,而不是 `wr_ptr` / `wr_ptr+1`:`wr_ptr+1` 只在"A 先命中"时
    //    成立,而折回之后 P=4 这类档位是 B 先命中(推导见文件头 ④)。
    //    独立指针 ⇒ 地址的奇偶与命中先后**无关**。
    wire [BUF_AW-1:0] wr_addr_a = {wr_a, 1'b0};
    wire [BUF_AW-1:0] wr_addr_b = {wr_b, 1'b1};

    wire wr_active = busy | cont_s;
    // ⚠️ `& ~go_pulse`:GO 与 samp_en 同拍时,指针正被清零,
    //    不屏蔽就会用**旧指针**写一拍。数据本身无害(下一圈覆盖),
    //    但会让 done 的判定多一拍不确定性 —— 屏蔽掉最省心。
    wire wr_en_a   = samp_en_a & wr_active & ~go_pulse;
    wire wr_en_b   = samp_en_b & wr_active & ~go_pulse;
    wire wr_en     = wr_en_a | wr_en_b;             // 同拍最多一个(见上面 ⚠️)
    wire [BUF_AW-1:0] wr_addr = samp_en_a ? wr_addr_a : wr_addr_b;
    wire wr_last   = (wr_n == (BUF_DEPTH - 1));     // 第 BUF_DEPTH 个字的写入

    always @(posedge clk_base or negedge rst_base_n) begin
        if (!rst_base_n) begin
            busy       <= 1'b0;
            done       <= 1'b0;
            wr_a       <= {CH_AW{1'b0}};
            wr_b       <= {CH_AW{1'b0}};
            wr_n       <= {BUF_AW{1'b0}};
            otr_sticky <= 1'b0;
        end else if (go_pulse) begin
            // 启动:清指针、清粘滞、进 busy。done 同时清掉 ——
            // 这是"读回即已生效"契约:PS 看到 done=1 时,缓冲必属于**本次**采集。
            busy       <= 1'b1;
            done       <= 1'b0;
            wr_a       <= {CH_AW{1'b0}};
            wr_b       <= {CH_AW{1'b0}};
            wr_n       <= {BUF_AW{1'b0}};
            otr_sticky <= 1'b0;
        end else if (wr_en) begin
            // 每路各自数满 CH_DEPTH 就绕回。⛔ 不要用 wr_a 去推 wr_b ——
            // 两路的命中先后随 P 变,唯一可靠的判据是"各自写了几次"。
            if (wr_en_a) wr_a <= (wr_a == CH_LAST) ? {CH_AW{1'b0}} : (wr_a + 1'b1);
            if (wr_en_b) wr_b <= (wr_b == CH_LAST) ? {CH_AW{1'b0}} : (wr_b + 1'b1);
            wr_n <= wr_last ? {BUF_AW{1'b0}} : (wr_n + 1'b1);
            if (adc_otr) otr_sticky <= 1'b1;
            if (wr_last) begin
                if (!cont_s) busy <= 1'b0;   // 单次:收满即停
                done <= 1'b1;                // 自由:每绕满一圈刷新一次
            end
        end
    end

    //=========================================================================
    //  6. 采集缓冲 —— 简单双口 BRAM(写 clk_base / 读 clk_axi)
    //     一个字 16 位:{3'b000, otr, 12 位采样} ⇒ [11:0] 采样、[12] OTR
    //     🔴 地址是**交织**的:偶 = A(INA)、奇 = B(INB),见文件头 ④。
    //        `wr_addr` 由"这一拍是哪一路命中"选出 —— 综合出来仍是**单写口**
    //        (同拍最多一路命中),不会退化成两个端口。
    //     ⚠️ 写口**不能**放在上面的控制 always 块里 —— 那样综合不出 BRAM。
    //=========================================================================
    // ⚠️ 名字不能叫 `buf` —— 那是 Verilog 的门原语保留字(VRFC 10-4982
    //    "syntax error near 'buf'",2026-10-06 实测踩到)。用 cap_mem。
    (* ram_style = "block" *) reg [15:0] cap_mem [0:BUF_DEPTH-1];

    //  🔴 **2026-10-12:AD9238 出的是二进制补码,这里转成偏移二进制。**
    //     板上实测(8190 点,1 MHz 激励,65 MSPS):
    //       按直通二进制读 → 峰峰恒 4095 码、均值 2046、二阶差分粗糙度 254.5、
    //                        1 MHz 相干幅度 2407 码但 SNR −2.4 dB(不是正弦)
    //       按二进制补码读 → 均值 −0.7、过零间隔 65.0 点(=1.0000 MHz)、
    //                        粗糙度 24.7、1 MHz 幅度 197 码、SNR +4.4 dB
    //     ⇒ 每个负半周被折到 `4096+|x|`,在屏上表现为"满幅方波"、
    //       在日志里表现为"峰峰 4095 码 / 直流停在半量程"。**不是 ADC 超量程**
    //       (0x90[3] otr 8190 点一次没置,真信号只占满量程 ~4.8%)。
    //     补码 → 偏移二进制就是翻 MSB:`0x000→0x800`、`0xFFF→0x7FF`,逐值可验。
    //     ⚠️ **下游 `adc_sample.c` 的文件头写着"假设直通二进制"—— 改这里之后
    //        那条假设才成立。不要再在 C 侧做一次同样的转换(会拐回来)。**
    //  🔴 **2026-10-14:OTR 位错了一个半字节 —— 写 [15]、读 [12],读回来恒 0。**
    //     原文 `{adc_otr, 3'b000, ...}` 把 otr 放在 **bit15**,
    //     而下面 `assign rd_otr = rd_r[12]` 取的是**填充位**。
    //     三个下游消费者写的都是 `[12] OTR` ——
    //       `src/python/cv_regs.py`(`"ADC_BUF_DATA": 0x98, # RO [11:0]sample [12]OTR`)
    //       `src/c_ui/app/pynq_regs.h`(`CV_ADC_OTR(d) = ((d)>>12)&1`)
    //       `tools/adc_probe.py`(打印 `[12]OTR`)
    //     ⇒ **单一事实源那一侧是对的,错的是这里的写。**
    //     后果:逐点 OTR 自设计起**从未置起来过** —— 屏上、日志里、探针里
    //     所有 `OTR 0` 都是"读的是个恒零位",不是"没溢出"。
    //     "波峰是不是超了上限"这个问题,系统里原本没有任何读数能回答。
    //     ⚠️ `0x90[3]` 那根**粘滞**标志走的是 `adc_otr` 引脚(见上面 otr_sticky),
    //        不经过这个字,**不受本缺陷影响** —— 两者别混为一谈。
    //     ⚠️ 只搬 OTR 这 4 位;采样仍是 `adc_d ^ 12'h800`(2026-10-12 的格式修正),
    //        两件事互不影响。
    always @(posedge clk_base) begin
        if (wr_en) cap_mem[wr_addr] <= {3'b000, adc_otr, (adc_d ^ 12'h800)};
    end

    reg [15:0] rd_r;

    always @(posedge clk_axi) begin
        rd_r <= cap_mem[rd_idx];    // 寄存器输出:比 rd_idx 晚一拍,见文件头说明
    end

    assign rd_data = rd_r[11:0];
    assign rd_otr  = rd_r[12];

    //=========================================================================
    //  7. 状态同步(clk_base → clk_axi)
    //     三个都只是电平,极性翻转远慢于 50 MHz ⇒ 两级同步足够。
    //=========================================================================
    (* ASYNC_REG = "TRUE" *) reg locked_s1, locked_s2;
    (* ASYNC_REG = "TRUE" *) reg done_s1,   done_s2;
    (* ASYNC_REG = "TRUE" *) reg busy_s1,   busy_s2;
    (* ASYNC_REG = "TRUE" *) reg otr_s1,    otr_s2;

    always @(posedge clk_axi) begin
        locked_s1 <= mmcm_locked;
        locked_s2 <= locked_s1;

        done_s1 <= done;    done_s2 <= done_s1;
        busy_s1 <= busy;    busy_s2 <= busy_s1;
        otr_s1  <= otr_sticky;  otr_s2 <= otr_s1;
    end

    assign sts_mmcm_locked = locked_s2;
    assign sts_done        = done_s2;
    assign sts_busy        = busy_s2;
    assign sts_otr         = otr_s2;

endmodule
