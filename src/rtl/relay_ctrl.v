//=============================================================================
//  relay_ctrl.v  ——  继电器矩阵 + 量程挡位控制(2026-10-10 新增)
//
//  归属:Claude 代写(用户 2026-10-10 明确要求「你直接分配引脚并且接入ps端写完」)
//        —— CLAUDE.md §6.0「代码由用户先写」的【显式例外】。
//
//  【本模块干什么】
//    把 0x1C(RELAY_CFG)/ 0x18(RANGE_SEL)两个寄存器的写入,变成物理引脚上的
//    7 根继电器线 + 4 根挡位线,期间做三件事:
//      ① 合法性互锁 —— 非法组合【拒收】,旧组合一位不动,并置 err_code;
//      ② 原子翻转   —— 7 位在同一拍同时改变(见下「为什么原子是白送的」);
//      ③ 硬件计时   —— 稳定延时在 PL 里倒计时,busy/done 由硬件给。
//
//  规格出处:report/source_design_checklist.md §2.1 R6(relay_ctrl)+ §3 寄存器表。
//    原文:「继电器时序状态机:先断后合、互锁、稳定延时 | cfg_relay → relay[7:0]
//           | 非法组合被拒绝并置 err_code」
//    ⚠️ 本文对该规格做了【三处偏离】,每一处都在下面写明理由,不是遗忘:
//       偏离 1:R6 要求「先断后合」。本实现**不做**两步切换 —— 见下 §原子翻转。
//       偏离 2:R6 说稳定延时单位是「周期数」。本实现单位是 **1 ms** —— 见 §稳定延时。
//       偏离 3:R6 写 `relay[7:0]`。本实现是 **`relay[6:0]`** —— 见 §位宽。
//
//=============================================================================
//  §与前序 STM32 工程的关系
//
//    本模块是 `qrs/Appli/Core/Src/relay_matrix.c` + `relay_controller.c` +
//    `acquisition_gain.c` 三个文件的 PL 化重写。
//    ★ 组合码表【逐字照抄】relay_matrix.c 的 #define,不是重新推导的 ——
//      那张表在 STM32 板上【实测跑通过】,是硬件证据;
//      而本项目的测试夹具原理图【不在手上】,没法制订「哪些组合会让栅极悬空」
//      的物理黑名单。代之以白名单,见 §组合白名单。
//
//=============================================================================
//  §原子翻转(偏离 1)—— 以及为什么「先断后合」在 PL 上是错的方向
//
//    STM32 侧 K1..K7 散在 PF9/PC0/PC3/PG14/PC1/PC2/PA3 【4 个 GPIO 端口】上。
//    一次 BSRR 只能原子改【同一个端口】的位 ⇒ 7 位要 4 次写,
//    **中间必然存在几百 ns 的过渡态**(relay_matrix.c 里那 4 行 BSRR 就是证据)。
//
//    PL 侧 7 位是同一个寄存器的 7 个 bit,同一拍输出 ⇒ **过渡态在物理上不存在**。
//    ⇒ 这是「搬到 PL」带来的一个真实收益,不只是「换个地方跑」。(B04 素材)
//
//    ⚠️ 因此**刻意不做**「先全断(AllOff)再合目标」的两步切换:
//       前序 relay_controller.c 的注释写得很清楚 ——
//         「直接施加目标继电器组合,**不插入 AllOff 中间状态**」。
//       插入 AllOff 会让 MOSFET 栅极【短暂悬空】,那才是危险态。
//       PL 上既然没有过渡态,两步切换就是【主动制造】一个原本不存在的危险窗口。
//
//=============================================================================
//  §稳定延时(偏离 2)
//
//    前序是 `RELAY_CONTROLLER_SWITCH_SETTLE_MS = 40` 在 MCU 里延时。
//    PS 侧若改用 time.sleep(0.04),会受 GIL / 调度抖动影响,而且
//    「延时完了没有」这个状态 PS 只能靠「睡够了」来假设。
//    放 PL:计满才置 done,PS 读 STATUS[1] 就是【已生效】,不是【已请求】。
//    ★ 与 0x60 LCD_SWAP 读回取 sts_lcd_status 是同一条原则
//      (见 cv_axi_lite_slave.v 文件尾 §设计决策备忘)。
//
//    🔴 **单位取 1 ms,不是规格写的「周期数」** —— 理由是宽度对不上:
//         40 ms @ 50 MHz = 2 000 000 拍 > 16 位(65535)。
//       规格把字段定成 [31:16] 16 位,若按周期数存,连一次 40 ms 都放不下。
//       ⇒ 取 1 ms 为单位:复位值 40 = 40 ms,与 STM32 的常量逐字相同;
//         16 位上限 65535 ms,余量充足。
//       ⛔ 规格原文需要同步修订 —— 否则下一个读规格的人会按周期数去填。
//
//    ⚠️ 计时精度取决于 clk_axi 的【真实】频率:
//       设计值 50 MHz / 真值 50.000 MHz(IO PLL 1000 / DIV0 20)。
//       但板上 BOOT.BIN 把 FCLK0 留在 **27.78 MHz**,直到 PS 调 apply_fclk0()。
//       ⇒ FCLK0 未修正时「40 ms」实际是 ~72 ms。**方向是安全的(只会更久)**,
//         且 PS 本来就应该先修 FCLK0 再动模拟前端(DAC 的复位图案是双向窗口,
//         比这里敏感得多,见 cv_axi_lite_slave.v 的 cfg_clk_release 长注释)。
//       ⛔ 报告里不得把 50 MHz 写成实测量。
//
//=============================================================================
//  §位宽(偏离 3)—— relay[6:0] 而不是 relay[7:0]
//
//    用户 2026-10-10 报出实际接线:继电器矩阵 **7 根**,球号
//      U15 U14 U13 V13 W11 Y11 Y12  → K1 K2 K3 K4 K5 K6 K7
//    ⇒ 端口是 7 位。0x1C 的 bit[7] 没有对应引脚:
//      · 本模块把 bit[7] 当**非法**处理(白名单里所有值 bit[7] 都是 0,
//        自然落进 default)⇒ 写 0x80 之类的值会被拒,不会静默忽略。
//    ⇒ 这是【有意】与规格的差异:写 8 位而只引出 7 位,会让 PS 以为
//      自己控制了一个不存在的继电器。
//
//    量程挡位 4 根,球号 Y13 V10 V11 W10 → A B C D:
//      A = 10 Ω  (gear[0])      C = 1 kΩ (gear[2])
//      B = 100 Ω (gear[1])      D = 10 kΩ(gear[3])
//      映射顺序 = 用户报出的顺序,已确认(`acquisition_gain.c` 的
//      GEAR_1..GEAR_4 = 10 Ω/100 Ω/1 kΩ/10 kΩ,逐位对齐)。
//
//=============================================================================
//  §组合白名单 —— 唯一合法形式就是这 7 个
//
//    逐字来自 relay_matrix.c(STM32 板上实测跑通的集合):
//      0x00  COSS_DISCHARGE  全断(放电态)
//      0x10  ALL_OFF         = K5       ← **复位值**,前序注释称其「安全状态」
//      0x1E  CISS_DISCHARGE  = K2 K3 K4 K5
//      0x3C  RG              = K3 K4 K5 K6
//      0x51  CRSS            = K1 K5 K7
//      0x61  COSS            = K1 K6 K7
//      0x7F  CISS            = K1..K7 全合
//    (前序还有 CRSS_DISCHARGE = K5 = 0x10,与 ALL_OFF 同值 ⇒ 去重后 7 个。)
//
//    ★ 为什么用白名单而不是规格建议的黑名单:
//      黑名单需要「哪些组合会栅极悬空 / 会让量程电阻短路」的物理判据,
//      而那要对着夹具原理图逐个回路推。原理图不在手上 ⇒ 推不出来。
//      白名单严格更安全:它连「未知的未来组合」一起挡。
//    ⚠️ 代价:将来若确需第 8 种组合,必须回来改这个 case,否则被拒收。
//      这是【有意】的取舍,不是遗漏 —— 拒收会置 err_code,PS 看得见。
//
//    ⚠️ 白名单挡的是「继电器组合」;挡不住的是【驱动板极性】:
//      本模块假定「引脚高 = 继电器闭合」(前序 RelayMatrix_WritePort 的写法,
//      asserted_pins 置高)。若实际驱动板是低有效,`ACTIVE_LOW` 参数改 1 即可,
//      见下 §参数。**这是上电第一件要核对的事**(听继电器咔哒声)。
//=============================================================================

module relay_ctrl #(
    // 1 ms 的拍数由这个常量的【设计值】折出来。★ 不是实测值。
    parameter integer CLK_FREQ_HZ = 50_000_000,

    // 驱动板极性。0 = 引脚高 = 继电器闭合(前序 STM32 的约定,默认);
    //             1 = 低有效(常见的光耦继电器板)。
    // ⚠️ 置 1 时 FPGA 配置期间(引脚全低)**所有继电器都会吸合** ——
    //    若驱动板是低有效且无上拉,这是个真实风险。改之前先量驱动板。
    parameter integer ACTIVE_LOW = 0
)(
    input  wire        clk,          // s_axi_aclk,设计 50 MHz
    input  wire        rst_n,        // s_axi_aresetn

    //-------------------------------------------------------------------------
    // 来自 cv_axi_lite_slave 的请求
    //   ⚠️ cfg_relay / cfg_gear 传的是**寄存器原值切好位宽后的结果**
    //      (cv_sys 在例化处切片,与 adc_capture 的 .cfg_div(cfg_adc_cfg[7:0])
    //       是同一个套路)⇒ 本模块的端口边界自带契约,读代码不用回查寄存器表。
    //-------------------------------------------------------------------------
    input  wire [7:0]  cfg_relay,       // 0x1C [7:0] 请求组合
    input  wire        cfg_relay_set,   // 0x1C 写 → 1 拍脉冲
    input  wire [3:0]  cfg_gear,        // 0x18 [3:0] 请求挡位(必须独热)
    input  wire        cfg_gear_set,    // 0x18 写 → 1 拍脉冲
    input  wire [15:0] cfg_settle_ms,   // 0x24 [31:16] 稳定时间,单位 **ms**

    //-------------------------------------------------------------------------
    // 物理引脚(cv_sys 直连顶层输出)
    //-------------------------------------------------------------------------
    output wire [6:0]  relay,           // K1..K7,bit0 = K1
    output wire [3:0]  gear,            // A B C D,bit0 = A(10 Ω)

    //-------------------------------------------------------------------------
    // 回给 cv_axi_lite_slave(0x1C / 0x18 / 0x04)
    //   ★ 这几个一律是【已生效】值,不是【已请求】值 —— 见上面 §稳定延时。
    //-------------------------------------------------------------------------
    output wire [7:0]  sts_relay_applied,   // → 0x1C 读
    output wire [3:0]  sts_gear_applied,    // → 0x18 读
    output wire [7:0]  sts_err_code,        // → STATUS(0x04)[15:8]
    output wire        sts_busy,            // → STATUS[0]
    output wire        sts_done             // → STATUS[1]
);

    //=========================================================================
    //  端口参数合法性自检(综合期常量,不耗逻辑)
    //=========================================================================
    // synopsys translate_off
    initial begin
        if (CLK_FREQ_HZ < 1_000) begin
            $display("ERROR: relay_ctrl: CLK_FREQ_HZ=%0d,1 ms 折不出整数拍", CLK_FREQ_HZ);
        end
    end
    // synopsys translate_on

    localparam integer MS_CYCLES_I = CLK_FREQ_HZ / 1_000;   // 1 ms 的拍数
    localparam [15:0]  MS_CYCLES   = MS_CYCLES_I[15:0];
    localparam         ACT_LOW     = (ACTIVE_LOW != 0);

    //-------------------------------------------------------------------------
    //  复位值
    //    RELAY_RESET = 8'h10 = ALL_OFF(K5)。
    //      出处:relay_matrix.c 的 RELAY_MATRIX_STATE_ALL_OFF,
    //      且 RelayMatrix_Init() 的注释写明「GPIO 切换为输出模式前先预装
    //      **工程定义的安全状态**」—— 作者本人把它定为安全态。
    //    GEAR_RESET  = 4'b0010 = B 档 = 100 Ω。
    //      出处:acquisition_gain.c 的 GetReferenceResistanceOhms() 默认返回
    //      100 Ω,且 Init() 预装 B 档。
    //    ⚠️ 这两个值【我没有独立复核过物理安全性】—— 夹具原理图不在手上。
    //       它们是从前序代码的**声明**搬过来的,不是从回路推出来的。
    //       上电第一次请按下面的顺序验:① 先不接 DUT ② 量 ALL_OFF 下
    //       DUT 三个端子的电位 ③ 确认无异常再上 DUT。
    //-------------------------------------------------------------------------
    localparam [7:0] RELAY_RESET = 8'h10;
    localparam [3:0] GEAR_RESET  = 4'b0010;

    //-------------------------------------------------------------------------
    //  错误码(STATUS[15:8])—— 粘滞,直到**下一次被受理的写**才清 0
    //    0x00 无错
    //    0x01 0x1C 组合不在白名单 ⇒ 拒收,旧组合保持
    //    0x02 0x18 挡位不是恰好一位 ⇒ 拒收,旧挡位保持
    //    0x03 0x1C 在稳定期内写入(busy)⇒ 拒收,旧组合保持
    //  ⚠️ 为什么取「粘滞到下次受理」而不是「只保持一拍」:
    //     PS 写坏值 → 读 0x1C 看到【旧值】→ 读 STATUS 看到 err_code,
    //     这条因果链是自洽的。若 err_code 只保持一拍,PS 那次读大概率错过,
    //     于是「写没生效」与「寄存器坏了」就分不开了。
    // ⚠️ 与 0x64 的粘滞位(lcd_fb_reader 的 underrun/axi_err,**写 0x64 清**)
    //    语义【不同】:那两个要能单独清,这两个不能。
    //    若将来需要「不写就清」,再加一条清零命令寄存器,不要偷偷改成
    //    「读一次清」。理由:CU 与 PS 并发读时,读副作用会引入新的撕裂源。
    //-------------------------------------------------------------------------
    localparam [7:0] ERR_NONE  = 8'h00;
    localparam [7:0] ERR_RELAY = 8'h01;
    localparam [7:0] ERR_GEAR  = 8'h02;
    localparam [7:0] ERR_BUSY  = 8'h03;

    //=========================================================================
    //  白名单 / 独热 判据(纯组合函数)
    //=========================================================================
    function automatic legal_relay;
        input [7:0] v;
        begin
            case (v)
                8'h00, 8'h10, 8'h1E, 8'h3C,
                8'h51, 8'h61, 8'h7F : legal_relay = 1'b1;
                default             : legal_relay = 1'b0;   // 含 bit[7]=1 的一切值
            endcase
        end
    endfunction

    function automatic legal_gear;
        input [3:0] v;
        begin
            case (v)
                4'b0001, 4'b0010, 4'b0100, 4'b1000 : legal_gear = 1'b1;
                default                            : legal_gear = 1'b0;   // 含 4'b0000
            endcase
        end
    endfunction

    //=========================================================================
    //  寄存器与计时器
    //=========================================================================
    reg [7:0]  relay_reg;       // 逻辑态:1 = 该继电器闭合
    reg [3:0]  gear_reg;        // 逻辑态:独热,1 = 该挡位投入
    reg [7:0]  err_code_r;
    reg        busy_r;
    reg        done_r;
    reg [15:0] ms_cnt;          // 1 ms 内的拍计数
    reg [15:0] settle_cnt;      // 还要等几个 ms

    // 1 ms 节拍。⚠️ 只在 busy 期间计数,空闲时清零 ——
    //   否则空闲时计数器自由跑,下一次进入 busy 会继承一个随机相位,
    //   稳定时间就会短最多 1 ms(不致命,但没有理由留这个不确定性)。
    wire ms_tick = busy_r && (ms_cnt == MS_CYCLES - 16'd1);

    always @(posedge clk) begin
        if (!rst_n) begin
            relay_reg  <= RELAY_RESET;
            gear_reg   <= GEAR_RESET;
            err_code_r <= ERR_NONE;
            busy_r     <= 1'b0;
            done_r     <= 1'b0;
            ms_cnt     <= 16'h0;
            settle_cnt <= 16'h0;
        end else begin
            //-----------------------------------------------------------------
            //  ① 1 ms 分频
            //-----------------------------------------------------------------
            if (busy_r) begin
                ms_cnt <= ms_tick ? 16'h0 : (ms_cnt + 16'd1);
            end else begin
                ms_cnt <= 16'h0;
            end

            //-----------------------------------------------------------------
            //  ② 稳定倒计时
            //     ⚠️ 本块写在 ③ ④【之前】—— 顺序有意:
            //        同一拍既有「倒计时到点」又有「新请求」时,由后面的 ③ 覆盖,
            //        ⇒ 新请求作废旧 done。若反过来,PS 会先看到 done=1
            //        (其实是上一轮的)再看到新组合,时序上说不清。
            //-----------------------------------------------------------------
            if (ms_tick) begin
                if (settle_cnt <= 16'd1) begin
                    busy_r     <= 1'b0;
                    done_r     <= 1'b1;      // ★ 「已生效」由硬件给,不是 PS 猜
                    settle_cnt <= 16'h0;
                end else begin
                    settle_cnt <= settle_cnt - 16'd1;
                end
            end

            //-----------------------------------------------------------------
            //  ③ 继电器请求(0x1C)
            //-----------------------------------------------------------------
            if (cfg_relay_set) begin
                if (busy_r) begin
                    // 正在稳定中 —— 拒收。照抄前序:RelayController_Request()
                    // 在非 STABLE 态直接 return false,不排队、不打断。
                    err_code_r <= ERR_BUSY;
                end else if (!legal_relay(cfg_relay)) begin
                    // ★ 拒收:relay_reg 一位都不动。PS 读 0x1C 会看到【旧值】,
                    //   读 STATUS 会看到 err_code = 0x01 —— 两处互相印证。
                    err_code_r <= ERR_RELAY;
                end else begin
                    relay_reg  <= cfg_relay;     // ★ 7 位同拍翻转,无过渡态
                    err_code_r <= ERR_NONE;      // 受理 ⇒ 清错
                    done_r     <= 1'b0;          // 新稳定期开始,上一轮的 done 作废
                    if (cfg_settle_ms == 16'h0) begin
                        // 延时 0 = 立即可用:不进 busy,本拍就结束
                        busy_r     <= 1'b0;
                        settle_cnt <= 16'h0;
                    end else begin
                        busy_r     <= 1'b1;
                        settle_cnt <= cfg_settle_ms;
                        ms_cnt     <= 16'h0;     // 相位归零,保证【至少】这么多 ms
                    end
                end
            end

            //-----------------------------------------------------------------
            //  ④ 挡位请求(0x18)
            //     ⚠️ 挡位**不进 busy、不占稳定计时器**,与继电器两条路完全独立。
            //        理由:① 前序 acquisition_gain.c 换挡就是立即生效、没有延时;
            //             ② 挡位是模拟开关(器件级 ns 建立),不是机械触点
            //                (继电器 ms 级),两者时间尺度差三个数量级,
            //                用同一个 40 ms 计时器是拿长的那把尺子量短的;
            //             ③ 挡位最坏情况是【量错】不是【损坏】(见下面独热的理由),
            //                而继电器组合错了才可能伤 DUT。
            //        ⇒ 若将来发现换挡后立刻采集会偏,把 ③ 的那几行复制过来即可。
            //-----------------------------------------------------------------
            if (cfg_gear_set) begin
                if (!legal_gear(cfg_gear)) begin
                    // ★ 必须恰好一位。两位置 1 ⇒ 两个 R0 电阻并联 ⇒ 阻值偏小,
                    //   而 PS 仍按它写进去的标称值反演 ⇒ 所有电容系统性偏大,
                    //   **不报错、不复位、不置 done** —— 最难查的那一类。
                    //   全 0 ⇒ R0 = ∞ ⇒ 开路,读数全是噪声。
                    //   ⇒ 两种都拒收,包括全 0。
                    err_code_r <= ERR_GEAR;
                end else begin
                    gear_reg   <= cfg_gear;
                    err_code_r <= ERR_NONE;
                end
            end
        end
    end

    //=========================================================================
    //  引脚输出 —— 极性在此处统一施加
    //    ⚠️ 寄存器与状态回读一律用**逻辑态**(1 = 闭合/投入),
    //       只在这一行翻转成物理电平。这样 PS 读 0x1C/0x18 拿到的
    //       与 STM32 侧那张码表可以直接比对,不受驱动板极性影响。
    //       ★ 若把极性施加在寄存器上,ACTIVE_LOW=1 时 PS 读回值与码表相反,
    //         两份文档立刻对不上 —— 那正是本项目反复吃的亏。
    //=========================================================================
    assign relay = ACT_LOW ? ~relay_reg[6:0] : relay_reg[6:0];
    assign gear  = ACT_LOW ? ~gear_reg       : gear_reg;

