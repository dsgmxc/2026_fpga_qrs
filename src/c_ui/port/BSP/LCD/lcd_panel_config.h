/**
 * @file lcd_panel_config.h
 * @brief 面板参数(PYNQ 版)—— 前序 STM32 同名头文件的替代
 *
 * ────────────────────────────────────────────────────────────────────────
 * 📌 这个目录 `port/BSP/...` 是**路径别名树**,不是随手起的名字:
 *    `ui_demo.c` 里写的是 `#include "BSP/LCD/lcd_panel_config.h"`,
 *    而我们**不改 ui_demo.c 一行**(为了能与前序工程逐字对照)。
 *    所以用 `-Iport` 把 `port/BSP/LCD/...` 映射过去。
 * ────────────────────────────────────────────────────────────────────────
 *
 * 与前序版本的差别(只有这些):
 *   · 删掉 LTDC 时序 / PLL3 配置宏 —— 那些是 STM32 LTDC 外设的寄存器参数,
 *     在 PYNQ 上**根本不存在**:时序由 PL 的 `lcd_timing` 产生。
 *     (`ui_demo.c` 从头到尾只用到 `LCD_PIXEL_WIDTH` / `LCD_PIXEL_HEIGHT`
 *      两个宏,已逐处核对。)
 *   · 面板固定为 ATK-MD0700R-1024600-IPS,不再保留 800×480 分支 ——
 *     本项目硬件已定,留一个用不到的编译分支只会让人以为"可以切"。
 */

#ifndef LCD_PANEL_CONFIG_H
#define LCD_PANEL_CONFIG_H

/* ------------------------------------------------------------------ */
/* 面板分辨率 —— 与 PL 侧 lcd_timing 的 H_DISP/V_DISP 必须一致          */
/* ------------------------------------------------------------------ */
#define LCD_PIXEL_WIDTH   1024
#define LCD_PIXEL_HEIGHT  600

#define LCD_PANEL_NAME    "ATK-MD0700R-1024600-IPS"

/* 像素格式:RGB565 存进 DDR,PL 展开成 RGB888 上屏(引脚仍是 24 根) */
#define LCD_BYTES_PER_PIXEL 2

/* ------------------------------------------------------------------ */
/* 触摸坐标变换                                                        */
/*   前序对这块 1024×600 面板三个宏**全是 0**(x/y 直通)。              */
/*   ⇒ 本工程照搬,不引入"反正能跑"的缩放。                             */
/*   ⚠️ 若 tools/touch_probe.py 实测发现**轴反了/交换了**,先查 GT911 的 */
/*      配置表,再考虑翻这里的宏 —— 但**不要**在这里加缩放系数:x/y 只有 */
/*      12 位,缩放会让"配置错了"永远查不出来。                          */
/* ------------------------------------------------------------------ */
#define LCD_TOUCH_SWAP_XY   0
#define LCD_TOUCH_INVERT_X  0
#define LCD_TOUCH_INVERT_Y  0

/* ------------------------------------------------------------------ */
/* PL 侧显示时序(仅作注释参考,PS 侧不产生时序)                        */
/*   出处:docs/display_subsystem.md §4.1                               */
/*   H_TOTAL = 1344 / V_TOTAL = 635 / PCLK = FCLK0                     */
/*   ⚠️ FCLK0 的设计值 50 MHz 与板上实测值可能不同 —— 见 CLAUDE.md §八  */
/* ------------------------------------------------------------------ */

#endif /* LCD_PANEL_CONFIG_H */
